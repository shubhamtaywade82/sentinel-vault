// server-only — bearer auth: admin + service-client realms.
// See VAULT_CONTRACT.md §2.

import { createHash, timingSafeEqual } from 'node:crypto'

import { db } from '@/lib/db'
import { assertProductionSecret } from './env'
import { VaultError } from './errors'
import type { ServiceClientRow, WorkspaceRow } from './types'

const DEFAULT_ADMIN_TOKEN = 'vault-admin-demo-token-CHANGE-ME'

// One-time startup assertion: in production the admin token MUST be set and
// MUST NOT be the known dev default. This runs at module-load time so a
// misconfigured production deployment fails fast instead of silently accepting
// the demo token.
assertProductionSecret('VAULT_ADMIN_TOKEN', process.env.VAULT_ADMIN_TOKEN, [
  DEFAULT_ADMIN_TOKEN,
])

export function getAdminToken(): string {
  return process.env.VAULT_ADMIN_TOKEN || DEFAULT_ADMIN_TOKEN
}

/** Constant-time string comparison. Returns true iff a === b (same length + bytes). */
export function timingEqual(a: string, b: string): boolean {
  const aBuf = Buffer.from(a, 'utf8')
  const bBuf = Buffer.from(b, 'utf8')
  if (aBuf.length !== bBuf.length) {
    // Still do a compare to keep timing roughly equal; result is false.
    try {
      timingSafeEqual(aBuf, bBuf)
    } catch {
      /* ignore */
    }
    return false
  }
  return timingSafeEqual(aBuf, bBuf)
}

/** sha256 hex digest of a string (used for credential digests + lookups). */
export function sha256Hex(s: string): string {
  return createHash('sha256').update(s, 'utf8').digest('hex')
}

export type AuthResult =
  | { kind: 'admin' }
  | { kind: 'client'; client: ServiceClientRow & { workspace: WorkspaceRow } }
  | { kind: 'none' }

export type RequireClientResult =
  | { kind: 'admin' }
  | { kind: 'client'; client: ServiceClientRow & { workspace: WorkspaceRow } }

function extractBearer(req: Request): string | null {
  const header = req.headers.get('authorization') || req.headers.get('Authorization')
  if (!header) return null
  const m = /^Bearer\s+(.+)$/i.exec(header.trim())
  if (!m) return null
  return m[1].trim()
}

/**
 * Resolve the bearer token into an admin, a service client, or "none".
 * Returns `{ kind: "none" }` (not throwing) when the token is missing/unknown
 * so route handlers can decide between 401 (no creds) vs 403 (admin_required).
 *
 * Side effect: on a successful client match with `status === "active"` and
 * not expired/revoked, we fire-and-forget update `lastUsedAt`. We deliberately
 * do NOT await this so a slow DB write never blocks the request path.
 */
export async function resolveAuth(req: Request): Promise<AuthResult> {
  const token = extractBearer(req)
  if (!token) return { kind: 'none' }

  if (timingEqual(token, getAdminToken())) {
    return { kind: 'admin' }
  }

  const digest = sha256Hex(token)
  // The Prisma client is generated by task 2-a; this call is typed once the
  // schema is pushed. Per the task instructions we do NOT regenerate here.
  const found = await db.serviceClient.findFirst({
    where: { credentialDigest: digest },
    include: { workspace: true },
  })

  if (!found) return { kind: 'none' }
  if (found.status !== 'active') return { kind: 'none' }
  if (found.revokedAt) return { kind: 'none' }
  if (found.expiresAt && new Date(found.expiresAt).getTime() < Date.now()) {
    return { kind: 'none' }
  }
  if (found.workspace && found.workspace.status !== 'active') {
    return { kind: 'none' }
  }

  // Fire-and-forget last-used touch.
  void db.serviceClient
    .update({ where: { id: found.id }, data: { lastUsedAt: new Date() } })
    .catch((err) => {
      // Never let a failed last-used write break the request flow.
      console.warn('[vault][auth] failed to update lastUsedAt:', err?.message)
    })

  return { kind: 'client', client: found as ServiceClientRow & { workspace: WorkspaceRow } }
}

/**
 * Throws `admin_required` unless the request is from the admin realm.
 */
export async function requireAdmin(req: Request): Promise<void> {
  const auth = await resolveAuth(req)
  if (auth.kind !== 'admin') {
    throw new VaultError('admin_required')
  }
}

/**
 * Flexible client/admin gate. Returns the resolved principal so the route can
 * decide how to handle admin-vs-client cases. Throws `unauthorized` when no
 * credential was supplied at all (kind === 'none'); admin is returned as
 * `{ kind: 'admin' }` and the route decides whether to allow it. Client-only
 * routes can opt to throw `admin_required` themselves if they want to deny.
 */
export async function requireClient(
  req: Request,
): Promise<RequireClientResult> {
  const auth = await resolveAuth(req)
  if (auth.kind === 'none') {
    throw new VaultError('unauthorized')
  }
  return auth
}

/**
 * Convenience: returns the ServiceClient row when the caller must be a
 * non-admin client (e.g. a client-scoped endpoint that explicitly excludes
 * the admin realm). Throws `admin_required` for admin and `unauthorized`
 * for missing creds.
 */
export async function requireClientOnly(
  req: Request,
): Promise<ServiceClientRow & { workspace: WorkspaceRow }> {
  const auth = await resolveAuth(req)
  if (auth.kind === 'none') throw new VaultError('unauthorized')
  if (auth.kind === 'admin') throw new VaultError('admin_required')
  return auth.client
}

export { VaultError }
